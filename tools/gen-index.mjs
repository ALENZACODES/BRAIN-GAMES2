// Regenerates js/games/index.js from the single-game files and the pack files, and checks every catalogue entry in range is playable.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { slug } from '../js/engine.js';
import { CONFIG } from '../js/config.js';
const dir = new URL('../js/games/', import.meta.url);
const singles = readdirSync(dir).filter((f) => f.endsWith('.js') && !f.startsWith('pack-') && f !== 'index.js').map((f) => f.replace('.js', ''));
const packs = readdirSync(dir).filter((f) => f.startsWith('pack-'));
const lines = ['// Generated by tools/gen-index.mjs. Do not edit by hand.', "const P = (f, id) => () => import(f).then((m) => ({ default: m.G.find((g) => g.id === id) }));", 'export const LIVE = {'];
for (const s of singles) lines.push(`  '${s}': () => import('./${s}.js'),`);
const ids = new Set(singles);
for (const p of packs) { const { G } = await import(new URL(p, dir)); for (const g of G) { if (ids.has(g.id)) throw new Error('duplicate ' + g.id); ids.add(g.id); lines.push(`  '${g.id}': P('./${p}', '${g.id}'),`); } }
lines.push('};', '');
writeFileSync(new URL('index.js', dir), lines.join('\n'));
const cat = JSON.parse(readFileSync(new URL('../js/catalog.json', import.meta.url))).filter((g) => g.n >= CONFIG.range[0] && g.n <= CONFIG.range[1]);
const missing = cat.filter((g) => !ids.has(slug(g.title)));
console.log(`${ids.size} live games; catalogue range has ${cat.length}; missing: ${missing.map((g) => g.n + ' ' + g.title).join(', ') || 'none'}`);
const extra = [...ids].filter((id) => !cat.some((g) => slug(g.title) === id)); if (extra.length) console.log('ids not in catalogue:', extra);
